import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The frame of a generated page of the documentation site (`client/public/docs/`, docs/docs-site.md) and the small
 * helpers its generators share: the plugin API reference (`plugin-api.mjs`, here) and the MCP tools reference
 * (`mcp/scripts/docs-reference.mjs`). A generated page says so in a comment at its top – it is never edited by hand.
 */

const here = path.dirname(fileURLToPath(import.meta.url));
export const DOCS = path.resolve(here, "../../../client/public/docs");

/** @param {unknown} text */
export const esc = text => String(text).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/**
 * Prose with `code` in backticks → HTML; a pipe inside stays text
 * @param {unknown} text
 */
export const inline = text => esc(String(text).replace(/\s+/g, " ").trim()).replace(/`([^`]+)`/g, "<code>$1</code>");

/**
 * An id for an anchor: letters, digits and dashes
 * @param {unknown} text
 */
export const slug = text => String(text).replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "");

/** @param {{ title: string, desc: string, kicker: string, lead: string, body: string, generator: string }} page – `lead` and `body` are HTML */
export const page = ({ title, desc, kicker, lead, body, generator }) => `<!doctype html>
<!-- Generated by ${generator} – do not edit; run it again instead (docs/docs-site.md "Reference pages"). -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>${esc(title)} – OSCT docs</title>
  <meta name="description" content="${esc(desc)}">
  <meta name="robots" content="noindex">
  <link rel="icon" href="/favicon.ico">
  <link rel="stylesheet" href="/docs/docs.css">
  <script src="/docs/docs.js" defer></script>
</head>
<body>
<nav id="nav" aria-label="Documentation"><a class="home" href="/docs/">OSCT docs</a></nav>
<main class="reference">
  <p class="kicker">${esc(kicker)}</p>
  <h1>${esc(title)}</h1>
  <p class="lead">${lead}</p>
  <nav id="toc" aria-label="On this page"></nav>
${body}
  <footer id="pager"></footer>
</main>
</body>
</html>
`;

/**
 * Writes the page, or with `check` compares it with the file there (line ends aside) and returns whether it is current
 * @param {string} relative the page's path below client/public/docs/
 * @param {string} html
 * @param {boolean} [check]
 */
export const write = (relative, html, check) => {
  const file = path.resolve(DOCS, relative);
  const text = html.replace(/\r\n/g, "\n");
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
    if (current === text) return true;
    console.error(`client/public/docs/${relative} is out of date – run the generator and commit it.`);
    return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`client/public/docs/${relative} (${Math.round(text.length / 1024)} kB)`);
  return true;
};
