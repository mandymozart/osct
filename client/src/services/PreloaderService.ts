import type { LoadOptions, LoadResult } from "@/types";
import { contentUrl, getAssets, getContentSizes, getNeighbourScenes, getScene, getScenes, getSubtitleFiles, getTargets, isContentUrl } from "@/utils/game-config";
import { compressedUrl } from "@/utils/compressed";
import { deviceHints, wantedTextureSize } from "@engine/scene/model-textures";
import { textureSizeFor } from "@shared/types/textures";
import { GraphicsService } from "./GraphicsService";

const DEFAULT_TIMEOUT = 30000;
/** Whole-experience download: timeout per file (large videos on slow connections) and parallel downloads */
const DOWNLOAD_TIMEOUT = 5 * 60000;
const DOWNLOAD_PARALLEL = 3;

/** Whole-experience download state (Info page) in bytes; `total` comes from the file sizes recorded at build time */
export interface ExperienceDownload {
  state: "idle" | "running" | "done" | "failed";
  loaded: number;
  total: number;
  /** Files that could not be downloaded (state `failed`) */
  failed: number;
}


/** A scene's target images: the tracker makes the engine's image targets from them (needed to start AR) */
const getTargetImages = (sceneId: string): LoadOptions[] =>
  getTargets(sceneId).map(t => t.imageSrc).filter(isContentUrl).map(src => ({ src, type: "image" }));

/**
 * Files a scene uses besides its target images: entity assets (AR models, images, audio, videos), the subtitle files
 * of its videos (every language – they are small) and entry images (consultation). Videos come last since they are the
 * largest. A model with a texture set (#260) brings its
 * map at the size the reader's texture quality asks for – the one size the AR scene loads, not the whole set.
 */
const getSceneContent = (sceneId: string): LoadOptions[] => {
  const wanted = wantedTextureSize(GraphicsService.getInstance().getSettings().textureQuality, deviceHints());
  const assets: LoadOptions[] = getAssets(sceneId)
    .filter(a => isContentUrl(a.src))
    .flatMap(a => [
      { src: compressedUrl(a.src), type: a.assetType }, // the same URL the AR scene loads
      ...(a.textures ?? []).map(set => textureSizeFor(set, wanted)?.src).filter(isContentUrl).map(src => ({ src, type: "image" as const })),
    ]);
  const images: LoadOptions[] = (getScene(sceneId)?.entries ?? [])
    .map(e => e.image)
    .filter(isContentUrl)
    .map(src => ({ src, type: "image" }));
  const subtitles: LoadOptions[] = getSubtitleFiles(sceneId).filter(isContentUrl).map(src => ({ src, type: "subtitles" }));
  const isVideo = (o: LoadOptions) => o.type === "video";
  return [...assets.filter(o => !isVideo(o)), ...subtitles, ...images, ...assets.filter(isVideo)];
};

/** Every content file of the experience – all scenes' target images, entity assets and entry images – each once */
const getExperienceContent = (): LoadOptions[] => {
  const seen = new Set<string>();
  return getScenes()
    .flatMap(s => [...getTargetImages(s.id), ...getSceneContent(s.id)])
    .filter(o => !seen.has(o.src) && !!seen.add(o.src));
};

/**
 * Content file sizes in bytes by URL: from the CDN content (`files.json`, loaded with the configuration) or,
 * for content served with the app, generated by vite.config.js `contentSizes` (separate chunk, loaded on demand)
 */
const loadContentSizes = async (): Promise<Record<string, number>> => {
  const fromCdn = getContentSizes();
  if (fromCdn) return fromCdn;
  const sizes: Record<string, number> = (await import("virtual:osct-content-sizes")).default;
  return Object.fromEntries(Object.entries(sizes).map(([path, size]) => [contentUrl(path), size]));
};

/**
 * Preloads files into the browser (HTTP) cache only (RULES.md #4): a plain fetch whose body is read and
 * discarded, so the later request by the tracker / three.js for the same URL is served from the cache.
 * Never touches the AR scene. One request per URL; failed ones may be retried.
 * In production the service worker stores what these fetches load (its content cache), which is also how
 * `downloadExperience()` puts the whole experience on the device.
 */
export class PreloaderService {
  private static instance: PreloaderService | null = null;
  private loads = new Map<string, Promise<LoadResult>>();
  private done = new Set<string>();
  private download: ExperienceDownload = { state: "idle", loaded: 0, total: 0, failed: 0 };
  private downloadRun: Promise<ExperienceDownload> | null = null;
  private downloadListeners = new Set<(download: ExperienceDownload) => void>();
  private windowRun = 0;

  static getInstance(): PreloaderService {
    if (!PreloaderService.instance) PreloaderService.instance = new PreloaderService();
    return PreloaderService.instance;
  }

  /** `onBytes` receives byte counts as they arrive, only when this call starts the request (not when joining a running one) */
  preload({ src, timeout = DEFAULT_TIMEOUT }: LoadOptions, onBytes?: (bytes: number) => void): Promise<LoadResult> {
    const running = this.loads.get(src);
    if (running) return running;

    const load = this.fetchIntoCache(src, timeout, onBytes).then(result => {
      if (result.success) this.done.add(src);
      else this.loads.delete(src); // allow a retry
      return result;
    });
    this.loads.set(src, load);
    return load;
  }

  isPreloaded(src: string): boolean {
    return this.done.has(src);
  }

  /** One scene: its target images first (needed to start AR), then entity assets and entry images */
  async preloadScene(sceneId: string): Promise<LoadResult[]> {
    if (!getScene(sceneId)) return [];
    const targets = await Promise.all(getTargetImages(sceneId).map(options => this.preload(options)));
    const content = await Promise.all(getSceneContent(sceneId).map(options => this.preload(options)));
    return [...targets, ...content];
  }

  /**
   * Content of the scenes adjacent to `sceneId` in experience order (the ones the scene menu reaches next).
   * Limited to neighbours: the experience has many scenes and their media add up.
   * Target images first (needed to start AR), then entity assets and entry images.
   */
  async preloadNeighbours(sceneId: string, range = 1): Promise<LoadResult[]> {
    const neighbours = getNeighbourScenes(sceneId, range);
    const targets = await Promise.all(neighbours.flatMap(s => getTargetImages(s.id)).map(options => this.preload(options)));
    const content = await Promise.all(neighbours.flatMap(s => getSceneContent(s.id)).map(options => this.preload(options)));
    return [...targets, ...content];
  }

  /**
   * Content of the scenes kept ready next to the current one (the tracker's window, nearest first): their target
   * images first (the tracker needs them), then each scene's assets and entry images, one scene at a time – the
   * nearest are ready first and a large window does not start every download at once. A newer call (the window
   * moved) stops the older one between scenes; what it fetched stays cached.
   */
  async preloadScenes(sceneIds: readonly string[]): Promise<LoadResult[]> {
    const run = ++this.windowRun;
    const ids = sceneIds.filter(id => getScene(id));
    const results = await Promise.all(ids.flatMap(id => getTargetImages(id)).map(options => this.preload(options)));
    for (const id of ids) {
      if (run !== this.windowRun) break;
      results.push(...await Promise.all(getSceneContent(id).map(options => this.preload(options))));
    }
    return results;
  }

  /**
   * Total size of the experience and how much of it is already on this device (service worker cache, or loaded in
   * this session). State is `done` when everything is stored.
   */
  async getExperienceDownload(): Promise<ExperienceDownload> {
    if (this.download.state === "running") return { ...this.download };
    const [files, sizes] = [getExperienceContent(), await loadContentSizes()];
    const stored = await Promise.all(files.map(f => this.isStored(f.src)));
    const total = files.reduce((sum, f) => sum + (sizes[f.src] ?? 0), 0);
    const loaded = files.reduce((sum, f, i) => sum + (stored[i] ? sizes[f.src] ?? 0 : 0), 0);
    const state = stored.every(Boolean) ? "done" : this.download.state === "failed" ? "failed" : "idle";
    this.download = { ...this.download, state, loaded, total };
    return { ...this.download };
  }

  /**
   * Downloads the whole experience (Info page): every content file not yet on the device, a few in parallel, with
   * progress in bytes. Only one run at a time; it continues after the Info page closes. Requests persistent
   * storage so the browser does not evict it when space runs low.
   */
  downloadExperience(): Promise<ExperienceDownload> {
    if (!this.downloadRun) this.downloadRun = this.runExperienceDownload().finally(() => { this.downloadRun = null; });
    return this.downloadRun;
  }

  /** Progress of the whole-experience download; returns the unsubscribe function */
  onExperienceDownload(listener: (download: ExperienceDownload) => void): () => void {
    this.downloadListeners.add(listener);
    return () => { this.downloadListeners.delete(listener); };
  }

  private async runExperienceDownload(): Promise<ExperienceDownload> {
    const [files, sizes] = [getExperienceContent(), await loadContentSizes()];
    const size = (src: string) => sizes[src] ?? 0;
    const total = files.reduce((sum, f) => sum + size(f.src), 0);
    void navigator.storage?.persist?.().catch(() => false);

    const stored = await Promise.all(files.map(f => this.isStored(f.src)));
    const queue = files.filter((_, i) => !stored[i]);
    let loaded = files.reduce((sum, f, i) => sum + (stored[i] ? size(f.src) : 0), 0);
    let failed = 0;
    const report = (state: ExperienceDownload["state"]) => {
      this.download = { state, loaded: Math.min(loaded, total), total, failed };
      this.downloadListeners.forEach(listener => listener({ ...this.download }));
    };
    report("running");

    const worker = async () => {
      for (let file = queue.shift(); file; file = queue.shift()) {
        let received = 0;
        const result = await this.preload({ ...file, timeout: DOWNLOAD_TIMEOUT }, bytes => {
          received += bytes;
          loaded += bytes;
          report("running");
        });
        // Count the build-time file size (received bytes differ when the server compresses the response)
        loaded += (result.success ? size(file.src) : 0) - received;
        if (!result.success) failed++;
        report("running");
      }
    };
    await Promise.all(Array.from({ length: DOWNLOAD_PARALLEL }, worker));
    report(failed ? "failed" : "done");
    return { ...this.download };
  }

  /** Stored on this device: in the service worker cache (production) or loaded in this session (HTTP cache) */
  private async isStored(src: string): Promise<boolean> {
    if (this.done.has(src)) return true;
    try {
      return typeof caches !== "undefined" && !!(await caches.match(src));
    } catch {
      return false;
    }
  }

  private async fetchIntoCache(src: string, timeout: number, onBytes?: (bytes: number) => void): Promise<LoadResult> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeout);
    try {
      const response = await fetch(src, { signal: controller.signal, priority: "low" } as RequestInit);
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      // The body must be read in full for the response to be cached
      if (onBytes && response.body) {
        const reader = response.body.getReader();
        for (let chunk = await reader.read(); !chunk.done; chunk = await reader.read()) onBytes(chunk.value.byteLength);
      } else {
        await response.arrayBuffer();
      }
      return { success: true };
    } catch (error) {
      console.warn(`[PreloaderService] Failed to preload ${src}:`, error);
      return { success: false, error: error instanceof Error ? error : new Error(String(error)) };
    } finally {
      clearTimeout(timer);
    }
  }
}
